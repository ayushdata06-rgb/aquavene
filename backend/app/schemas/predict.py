"""Pydantic v2 schemas for Geospatial and ML Predictions."""

from __future__ import annotations

import uuid
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class FeatureVector(BaseModel):
    """12 Zonal and Hydrological features extracted from AOI."""
    mean_slope_deg: float = Field(..., description="Zonal mean slope in degrees from WhiteboxTools")
    elevation_range_m: float = Field(..., description="Relief elevation difference max - min")
    bare_soil_pct: float = Field(..., description="Percentage bare soil pixels")
    drainage_density: float = Field(..., description="Stream channel length per unit area km/km2")
    flow_accumulation_p95: float = Field(..., description="95th percentile D8 flow accumulation")
    rainfall_intensity_idf: float = Field(..., description="IMD 1-hour P50 rainfall intensity mm/hr")
    forest_cover_pct: float = Field(..., description="Forest and dense tree canopy fraction")
    crop_land_pct: float = Field(..., description="Agricultural arable land fraction")
    imperviousness_pct: float = Field(..., description="Built-up settlements and hard surface fraction")
    soil_erodibility_k: float = Field(..., description="USLE K-factor zonal mean")
    sediment_delivery_ratio: float = Field(..., description="Catchment sediment delivery ratio SDR")
    stream_power_index: float = Field(..., description="SPI = flow_accum * tan(slope)")

    model_config = ConfigDict(from_attributes=True)


class USLEFactors(BaseModel):
    """Universal Soil Loss Equation parameters: A = R * K * LS * C * P"""
    r_factor: float = Field(892.0, description="Rainfall-runoff erosivity index")
    k_factor: float = Field(0.38, description="Soil erodibility factor")
    ls_factor: float = Field(4.2, description="Slope length and steepness factor")
    c_factor: float = Field(0.65, description="Cover-management factor")
    p_factor: float = Field(1.0, description="Support practice factor")
    annual_soil_loss_t_ha_yr: float = Field(..., description="Computed soil loss tons/ha/year")


class WhiteboxResult(BaseModel):
    """Hydrological outputs generated by WhiteboxTools 2.3 pipeline."""
    stream_network_geojson: Dict[str, Any] = Field(default_factory=dict)
    watershed_polygons_geojson: Dict[str, Any] = Field(default_factory=dict)
    flow_accumulation_stats: Dict[str, float] = Field(default_factory=dict)
    slope_stats: Dict[str, float] = Field(default_factory=dict)
    drainage_density_km_per_km2: float = 2.4
    sink_count: int = 0
    strahler_order_distribution: Dict[str, int] = Field(default_factory=dict)
    pour_points: List[Dict[str, Any]] = Field(default_factory=list)


class VulnerabilityResult(BaseModel):
    """Composite Priority Vulnerability Index (PVI) prediction."""
    pvi_score: float = Field(..., ge=0, le=100)
    risk_level: str = Field(..., description="low, medium, high, or critical")
    component_scores: Dict[str, float] = Field(
        ..., description="Sub-indices: E (Erosion), R (Runoff), L (Land), W (Water), D (Drainage)"
    )
    confidence: float = Field(0.92, ge=0, le=1.0)
    shap_values: Dict[str, float] = Field(default_factory=dict)
    top_drivers: List[Dict[str, Any]] = Field(default_factory=list)


class SHAPResult(BaseModel):
    base_value: float = 50.0
    shap_values: Dict[str, float] = Field(default_factory=dict)
    top_drivers: List[Dict[str, Any]] = Field(default_factory=list)


class InterventionLevers(BaseModel):
    """6 Civil and Agro-Ecological Restoration Levers."""
    reforest_pct: float = Field(0.0, ge=0, le=100)
    check_dams_count: int = Field(0, ge=0, le=50)
    cct_pct: float = Field(0.0, ge=0, le=100)
    stream_repair_km: float = Field(0.0, ge=0, le=100)
    road_stabilisation_km: float = Field(0.0, ge=0, le=50)
    cover_crop_pct: float = Field(0.0, ge=0, le=100)


class HydrographPoint(BaseModel):
    hour: int
    discharge_m3s: float


class HydrographResult(BaseModel):
    """Counterfactual 72-hour storm hydrograph simulation output."""
    baseline_hydrograph: List[HydrographPoint]
    restored_hydrograph: List[HydrographPoint]
    peak_reduction_pct: float
    time_to_peak_baseline_hr: float
    time_to_peak_restored_hr: float
    flood_threshold_m3s: float
    hours_above_threshold_baseline: int
    hours_above_threshold_restored: int
    annual_soil_loss_baseline: float
    annual_soil_loss_restored: float
    total_water_stored_m3: float
    carbon_sequestration_t_co2_yr: float


class AOIPredictRequest(BaseModel):
    geojson: Dict[str, Any]
    name: Optional[str] = "Custom Study Area"
    options: Optional[Dict[str, Any]] = Field(default_factory=dict)


class AOIPredictResponse(BaseModel):
    area_name: str
    area_sq_km: float
    centroid: List[float]
    features: FeatureVector
    vulnerability: VulnerabilityResult
    whitebox: Optional[WhiteboxResult] = None
    usle: USLEFactors
    processing_job_id: Optional[uuid.UUID] = None


class SimulateRequest(BaseModel):
    geojson: Optional[Dict[str, Any]] = None
    levers: InterventionLevers
    base_features: Optional[FeatureVector] = None
    # Backward compatibility with flat payload
    reforest_bare_soil_pct: Optional[float] = None
    add_check_dams_count: Optional[int] = None
    cct_ridge_coverage_pct: Optional[float] = None


class SimulateResponse(BaseModel):
    hydrograph: HydrographResult
    simulated_score: float
    simulated_category: str
    score_delta: float
    reduction_pct: float
    new_soil_loss_t_ha_yr: float
    modified_features: Dict[str, float] = Field(default_factory=dict)
